const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'sources/UniDSAFocusControlRuntime.js'), 'utf8').replace(/^\uFEFF/, '').replace(/\r\n/g, '\n');
const result = '// Generated by tools/embed-focus-runtime.cjs. Edit UniDSAFocusControlRuntime.js instead.\nconst\n  UniDSAFocusControlRuntime =\n' + source.trimEnd().split('\n').map((line, i, lines) => "    '" + line.replace(/'/g, "''") + "'" + (i === lines.length - 1 ? ';' : ' + #10 +')).join('\n') + '\n';
const target = path.join(root, 'sources/UniDSAFocusControlRuntime.inc');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== result) throw new Error('Run node tools/embed-focus-runtime.cjs to update the embedded runtime.');
} else fs.writeFileSync(target, result, 'utf8');
